/** 본문에서 찾을 때는 긴 말부터 — 「독립공채」가 「공채」보다 먼저 걸려야 한다. */
export const glossaryTerms: Array<{ key: string; entry: GlossaryEntry }> = glossary
  .flatMap((entry) => [entry.term, ...(entry.aliases ?? [])].map((key) => ({ key, entry })))
  .sort((a, b) => b.key.length - a.key.length);

export function findGlossary(word: string): GlossaryEntry | undefined {
  return glossaryTerms.find((t) => t.key === word)?.entry;
}
