export function getQuest(id: string): Quest {
  const found = quests.find((q) => q.id === id);
  if (!found) throw new Error(`알 수 없는 퀘스트 id: ${id}`);
  return found;
}

/** 특정 맵에서 지금 받을 수 있는 퀘스트 */
export function questsForMap(mapId: string): Quest[] {
  return quests.filter((q) => q.map === mapId);
}

/** 어떤 인물이 주는 퀘스트 */
export function questsByGiver(figureId: string): Quest[] {
  return quests.filter((q) => q.giver === figureId);
}
