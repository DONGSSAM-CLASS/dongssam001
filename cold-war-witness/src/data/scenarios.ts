const CHAPTER_MAP = new Map(CHAPTERS.map((c) => [c.id, c]));

export function getChapter(id: ChapterId): Chapter {
  const chapter = CHAPTER_MAP.get(id);
  if (!chapter) throw new Error(`챕터를 찾을 수 없어요: ${id}`);
  return chapter;
}

