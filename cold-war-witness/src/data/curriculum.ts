export function getKselCompetency(id: KselId): KselCompetency {
  const c = KSEL_COMPETENCIES.find((x) => x.id === id);
  if (!c) throw new Error(`K-SEL 역량을 찾을 수 없어요: ${id}`);
  return c;
}

export function getKselStandard(code: KselStandardCode): KselStandard {
  const s = KSEL_STANDARDS.find((x) => x.code === code);
  if (!s) throw new Error(`K-SEL 성취기준을 찾을 수 없어요: ${code}`);
  return s;
}

