export const PRODUCT_TYPES = {
  'lesson-pack': '교사용 수업 자료 패키지 (개념 정리 + 활동 + 학생 활동지 + 정답·해설 + 지도 유의점)',
  'study-guide': '학생·학부모용 자기주도 학습 노트 (개념 정리 + 확인 문제 + 정답·해설, 가정에서 혼자 풀 수 있게)',
};

export const PRODUCT_SYSTEM = `당신은 한국 중·고등학교 역사 교육 콘텐츠를 만드는 현직 교사 겸 교재 편집자입니다.
돈을 받고 파는 디지털 자료를 만들기 때문에, 구매자가 "값어치를 한다"고 느낄 만큼 바로 수업·학습에 쓸 수 있어야 합니다.

반드시 지킬 것:
- 모든 문장은 직접 새로 씁니다. 교과서·참고서·기출문제 문장을 그대로 옮기지 않습니다(저작권).
- 사실 정확성이 최우선입니다. 연도·수치·인물 발언 인용처럼 틀리기 쉬운 내용은 본문에 쓰되 factCheck 목록에 빠짐없이 올립니다.
- 성취기준 코드 번호나 출처 문헌을 지어내지 않습니다. 확실하지 않으면 일반적인 표현으로 쓰고, 확인 방법을 적습니다.
- 2022 개정 교육과정 수준과 대상 학년의 어휘 수준에 맞춥니다.
- 한쪽 시각에 치우친 해석은 피하고, 논쟁적인 해석은 "~라는 견해가 있다"처럼 구분해 씁니다.
- 객관식은 보기 5개, 정답은 하나입니다. 서술형은 채점 기준이 드러나는 모범 답안을 씁니다.`;

export function productPrompt({ topic, grade, type, questions, note }) {
  const lines = [
    `주제: ${topic}`,
    `대상: ${grade}`,
    `상품 유형: ${PRODUCT_TYPES[type]}`,
    `평가 문항 수: ${questions}개 (객관식 위주, 서술형 1~2개 포함)`,
  ];
  if (note) lines.push(`추가 요청: ${note}`);
  lines.push('', '위 조건으로 판매용 자료 한 세트를 만들어 주세요.');
  return lines.join('\n');
}

export const MARKETING_SYSTEM = `당신은 교육 디지털 상품을 파는 1인 판매자의 마케팅 담당자입니다.
이미 완성된 자료를 받아 판매 페이지 문구, 검색 유입용 블로그 글, SNS 홍보 글, 숏폼 영상 대본을 씁니다.

반드시 지킬 것:
- 자료에 실제로 들어 있는 것만 소개합니다. "성적 보장", "100% 적중" 같은 과장·허위 표현은 쓰지 않습니다.
- 판매처마다 독자가 다릅니다. 교사 대상이면 수업 준비 시간 절약·바로 인쇄, 학부모·학생 대상이면 혼자 공부 가능함을 강조합니다.
- 가격은 원 단위 정수로, 국내 교육 자료·전자책 시장에서 무리 없는 범위로 제안하고 근거를 씁니다.
- 블로그 글은 그 자체로 읽을 가치가 있어야 합니다(자료 일부를 무료로 공개). 판매 안내는 끝에 한 번만 합니다.
- 해시태그·태그는 실제로 사람들이 검색할 만한 한국어 표현으로 씁니다.`;

export function marketingPrompt({ product, platforms }) {
  return [
    `판매처: ${platforms.join(', ')}`,
    '',
    '완성된 자료(JSON):',
    JSON.stringify(product, null, 2),
    '',
    '판매처마다 listings 항목을 하나씩 만들고, 블로그 글·SNS 글(인스타그램, 스레드, 네이버 밴드)·숏폼 대본을 써 주세요.',
  ].join('\n');
}

// 웹 화면(claude.ai 아티팩트)에서는 시스템 프롬프트를 따로 줄 수 없어 한 덩어리로 합친다.
export function jsonOnlyPrompt(system, user, jsonSchema) {
  return [
    system,
    '',
    user,
    '',
    '아래 JSON 스키마에 맞는 JSON 객체 하나만 출력하세요. 설명이나 코드 블록 표시 없이 JSON만 씁니다.',
    JSON.stringify(jsonSchema),
  ].join('\n');
}
